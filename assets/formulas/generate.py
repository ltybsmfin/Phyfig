"""Compile trusted project LaTeX formulas with MiKTeX and cache alpha masks.

Run from any directory: python path/to/formulas/generate.py
Requires pdflatex, pypdfium2 and Pillow. Normal C++ builds use the checked-in cache.
"""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from PIL import Image
import pypdfium2 as pdfium

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORK = ROOT / 'build' / 'latex-formulas'
WORK.mkdir(parents=True, exist_ok=True)
source = HERE / 'formulas.json'
formulas = json.loads(source.read_text(encoding='utf-8'))
latex = shutil.which('pdflatex')
if not latex:
    raise SystemExit('MiKTeX pdflatex must be on PATH')
tex = [r'\documentclass[12pt]{article}', r'\usepackage{amsmath}', r'\pagestyle{empty}', r'\begin{document}']
for formula in formulas.values():
    tex.append(r'\shipout\hbox{$\displaystyle ' + formula + r'$}')
tex.append(r'\end{document}')
(WORK / 'formulas.tex').write_text('\n'.join(tex), encoding='ascii')
subprocess.run([latex, '--disable-installer', '-no-shell-escape', '-interaction=nonstopmode',
                '-halt-on-error', 'formulas.tex'], cwd=WORK, check=True, timeout=90)
pdf = pdfium.PdfDocument(WORK / 'formulas.pdf')
if len(pdf) != len(formulas):
    raise RuntimeError('Formula page count mismatch')
lines = ['// Generated by formulas/generate.py; do not hand-edit.', '#pragma once',
         '#include <cstddef>', 'namespace formula_cache {',
         'struct Entry { const char* name; int width, height; const unsigned char* rle; std::size_t bytes; };']
entries = []
for page, name in enumerate(formulas, 1):
    bitmap = pdf[page-1].render(scale=240/72, fill_color=(255,255,255,0)).to_pil().convert('RGBA')
    alpha = bitmap.getchannel('A')
    if not alpha.getbbox():
        raise RuntimeError(f'Empty formula: {name}')
    alpha = alpha.crop(alpha.getbbox())
    preview = Image.new('RGBA',alpha.size,(255,255,255,0))
    preview.putalpha(alpha)
    preview.save(WORK / f'formula-{page}.png')
    # One transparent pixel border prevents neighbouring atlas entries bleeding.
    padded = Image.new('L', (alpha.width+2, alpha.height+2))
    padded.paste(alpha, (1,1))
    raw = padded.tobytes()
    encoded = []
    i = 0
    while i < len(raw):
        end = i+1
        while end < min(i+255, len(raw)) and raw[end] == raw[i]:
            end += 1
        encoded.extend((end-i, raw[i])); i = end
    lines.append(f'inline constexpr unsigned char data_{name}[] = {{')
    for offset in range(0, len(encoded), 80):
        lines.append(','.join(map(str, encoded[offset:offset+80])) + ',')
    lines.append('};')
    entries.append(f'{{"{name}",{padded.width},{padded.height},data_{name},sizeof(data_{name})}}')
lines.extend(['inline constexpr Entry entries[] = {', ',\n'.join(entries), '};',
              'inline constexpr float displayScale = 0.5f;',
              f'inline constexpr const char* sourceHash = "{hashlib.sha256(source.read_bytes()).hexdigest()}";', '}'])
(HERE / 'formula_cache.hpp').write_text('\n'.join(lines)+'\n', encoding='ascii')
print(f'Cached {len(entries)} genuine LaTeX formulas into formula_cache.hpp')


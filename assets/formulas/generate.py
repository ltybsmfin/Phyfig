"""Compile trusted project LaTeX formulas with MiKTeX and cache alpha masks.

Run from any directory: python path/to/formulas/generate.py
Requires pdflatex, pypdfium2 and Pillow. Normal C++ builds use the checked-in cache.

Two files are generated:

* ``formula_cache.hpp`` — the alpha masks (unchanged procedure, one page per
  formula, rendered at 240 DPI and cropped to the ink bounding box);
* ``formula_writing_plan.hpp`` — the optional structural writing plan of every
  built-in formula (see tools/formula_writing_plan.py). It only reorders and
  groups the mask's ink regions, so it cannot change the alpha data.

``--output DIR`` writes the headers to another directory, which is what the
sandbox/verification runs use; the alpha file is then compared byte for byte
against the checked-in one to prove the cache did not move.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
from PIL import Image
import pypdfium2 as pdfium

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORK = ROOT / 'build' / 'latex-formulas'
sys.path.insert(0, str(ROOT / 'tools'))
import formula_writing_plan  # noqa: E402


def _rle(raw):
    encoded = []
    index = 0
    while index < len(raw):
        end = index + 1
        while end < min(index + 255, len(raw)) and raw[end] == raw[index]:
            end += 1
        encoded.extend((end - index, raw[index]))
        index = end
    return encoded


def _compile(latex, work, tex):
    (work / 'formulas.tex').write_text('\n'.join(tex), encoding='ascii')
    subprocess.run([latex, '--disable-installer', '-no-shell-escape', '-interaction=nonstopmode',
                    '-halt-on-error', 'formulas.tex'], cwd=work, check=True, timeout=90)


def generate(output=HERE, work=WORK):
    """Regenerates both headers; returns the names of the formulas that were cached."""
    work.mkdir(parents=True, exist_ok=True)
    source = HERE / 'formulas.json'
    formulas = json.loads(source.read_text(encoding='utf-8'))
    latex = shutil.which('pdflatex')
    if not latex:
        raise SystemExit('MiKTeX pdflatex must be on PATH')
    tex = [r'\documentclass[12pt]{article}', r'\usepackage{amsmath}', r'\pagestyle{empty}', r'\begin{document}']
    for formula in formulas.values():
        tex.append(r'\shipout\hbox{$\displaystyle ' + formula + r'$}')
    tex.append(r'\end{document}')
    _compile(latex, work, tex)
    pdf = pdfium.PdfDocument(work / 'formulas.pdf')
    if len(pdf) != len(formulas):
        raise RuntimeError('Formula page count mismatch')
    lines = ['// Generated by formulas/generate.py; do not hand-edit.', '#pragma once',
             '#include <cstddef>', 'namespace formula_cache {',
             'struct Entry { const char* name; int width, height; const unsigned char* rle; std::size_t bytes; };']
    plan_lines = ['// Generated by formulas/generate.py; do not hand-edit.', '#pragma once',
                  '// Structural writing order of every built-in formula mask, produced from the',
                  '// same PDF pages as formula_cache.hpp by tools/formula_writing_plan.py.',
                  'namespace formula_writing_plan {',
                  '// kind: 0 = glyph, 1 = rule (fraction bar, radical overbar, overline).',
                  'struct Unit { const int* components; int count; int kind; };',
                  'struct Entry { const char* name; int width, height, componentCount; const Unit* units; int unitCount; };']
    entries, plan_entries = [], []
    for page, name in enumerate(formulas, 1):
        pdf_page = pdf[page - 1]
        bitmap = pdf_page.render(scale=240 / 72, fill_color=(255, 255, 255, 0))
        try:
            rendered = bitmap.to_pil()
            image_size = rendered.size
            alpha = rendered.convert('RGBA').getchannel('A')
        finally:
            bitmap.close()
        page_size = pdf_page.get_size()
        if not alpha.getbbox():
            raise RuntimeError(f'Empty formula: {name}')
        crop = alpha.getbbox()
        alpha = alpha.crop(crop)
        preview = Image.new('RGBA', alpha.size, (255, 255, 255, 0))
        preview.putalpha(alpha)
        preview.save(work / f'formula-{page}.png')
        # One transparent pixel border prevents neighbouring atlas entries bleeding.
        padded = Image.new('L', (alpha.width + 2, alpha.height + 2))
        padded.paste(alpha, (1, 1))
        raw = padded.tobytes()
        encoded = _rle(raw)
        lines.append(f'inline constexpr unsigned char data_{name}[] = {{')
        for offset in range(0, len(encoded), 80):
            lines.append(','.join(map(str, encoded[offset:offset + 80])) + ',')
        lines.append('};')
        entries.append(f'{{"{name}",{padded.width},{padded.height},data_{name},sizeof(data_{name})}}')
        atoms = formula_writing_plan.extract_atoms(pdfium, pdf_page)
        plan = formula_writing_plan.build_plan(atoms, raw, padded.width, padded.height,
                                               (crop[0], crop[1]), page_size, image_size)
        flat, units = [], []
        for unit in plan['units']:
            offset, count = len(flat), len(unit['components'])
            flat.extend(unit['components'])
            units.append('{plan_%s+%d,%d,%d}' % (name, offset, count, 1 if unit['kind'] == 'rule' else 0))
        plan_lines.append('inline constexpr int plan_%s[] = {%s};' % (name, ','.join(map(str, flat))))
        plan_lines.append('inline constexpr Unit units_%s[] = {%s};' % (name, ','.join(units)))
        plan_entries.append('{"%s",%d,%d,%d,units_%s,%d}' % (name, plan['width'], plan['height'],
                                                             plan['componentCount'], name, len(units)))
        pdf_page.close()
    lines.extend(['inline constexpr Entry entries[] = {', ',\n'.join(entries), '};',
                  'inline constexpr float displayScale = 0.5f;',
                  f'inline constexpr const char* sourceHash = "{hashlib.sha256(source.read_bytes()).hexdigest()}";', '}'])
    plan_lines.extend(['inline constexpr Entry entries[] = {', ',\n'.join(plan_entries), '};', '}'])
    # Explicit LF: the checked-in headers are exact-byte resources (see
    # .gitattributes), so regenerating them on Windows must not turn every line
    # into CRLF and report a whole-file change.
    (output / 'formula_cache.hpp').write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    (output / 'formula_writing_plan.hpp').write_text('\n'.join(plan_lines) + '\n', encoding='ascii', newline='\n')
    pdf.close()
    print(f'Cached {len(entries)} genuine LaTeX formulas into formula_cache.hpp')
    print(f'Wrote {len(plan_entries)} writing plans into formula_writing_plan.hpp')
    return list(formulas)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Cache built-in LaTeX formula masks and writing plans')
    parser.add_argument('--output', type=Path, default=HERE,
                        help='directory for formula_cache.hpp and formula_writing_plan.hpp')
    parser.add_argument('--work', type=Path, default=WORK, help='scratch directory for the PDF')
    arguments = parser.parse_args(argv)
    generate(arguments.output, arguments.work)


if __name__ == '__main__':
    main()
